#!/usr/bin/env python3
"""Reproducible real-crypto sweeps, optionally on isolated Linux tc links.

No host interface, routing table, or existing qdisc is modified. Network namespaces
and their veth pair are uniquely named and removed in a finally block.
"""
import argparse
import contextlib
import hashlib
import itertools
import json
import os
import pathlib
import platform
import shutil
import subprocess
import sys
import time
import uuid


PROFILES = {
    "tcp": (None, 0),
    "lan": (1000, 0.2),
    "metro": (100, 10),
    "wan": (100, 40),
    "slow": (10, 40),
}


def run(*args):
    return subprocess.run(args, check=True, capture_output=True, text=True)


@contextlib.contextmanager
def link(profile):
    if not hasattr(os, "geteuid") or os.geteuid() != 0:
        raise RuntimeError("tc profiles require Linux root (sudo); local needs no privileges")
    for tool in ("ip", "tc"):
        if not shutil.which(tool):
            raise RuntimeError(f"required tool missing: {tool}")
    stem = f"logstar-{os.getpid()}-{uuid.uuid4().hex[:6]}"
    names = [stem + "a", stem + "b"]
    # Linux interface names are limited to 15 bytes.
    devices = ["ls" + uuid.uuid4().hex[:9] + c for c in "ab"]
    created = []
    veth_created = False
    try:
        for name in names:
            run("ip", "netns", "add", name)
            created.append(name)
        run("ip", "link", "add", devices[0], "type", "veth", "peer", "name", devices[1])
        veth_created = True
        for i, (name, dev) in enumerate(zip(names, devices)):
            run("ip", "link", "set", dev, "netns", name)
            run("ip", "-n", name, "link", "set", "lo", "up")
            run("ip", "-n", name, "addr", "add", f"10.203.0.{i+1}/24", "dev", dev)
            run("ip", "-n", name, "link", "set", dev, "up")
            rate, rtt_ms = PROFILES[profile]
            if rate:
                run("ip", "netns", "exec", name, "tc", "qdisc", "add", "dev", dev,
                    "root", "netem", "limit", "100000", "delay", f"{rtt_ms / 2}ms",
                    "rate", f"{rate}mbit")
        yield names
    finally:
        for name in reversed(created):
            subprocess.run(["ip", "netns", "delete", name], check=False,
                           stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        if veth_created:
            # If moving an endpoint failed, it may still be in the host namespace.
            # These names were freshly generated by this invocation only.
            for dev in devices:
                subprocess.run(["ip", "link", "delete", dev], check=False,
                               stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def records(stdout):
    result = []
    for line in stdout.splitlines():
        if line.startswith("{"):
            result.append(json.loads(line))
    if not result:
        raise RuntimeError("benchmark produced no JSON records: " + stdout[-2000:])
    return result


def trial(exe, options, profile, timeout):
    if profile == "local":
        p = subprocess.Popen([str(exe), *options], stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
        deadline = time.monotonic() + timeout
        peak_swap = peak_rss = samples = 0
        try:
            while True:
                status = pathlib.Path(f"/proc/{p.pid}/status")
                try:
                    fields = dict(line.split(':', 1) for line in status.read_text().splitlines() if ':' in line)
                    peak_swap = max(peak_swap, int(fields.get('VmSwap', '0 kB').split()[0]))
                    peak_rss = max(peak_rss, int(fields.get('VmRSS', '0 kB').split()[0]))
                    samples += 1
                except FileNotFoundError:
                    pass
                if time.monotonic() >= deadline:
                    raise subprocess.TimeoutExpired(p.args, timeout)
                try:
                    stdout, stderr = p.communicate(timeout=min(0.5, deadline - time.monotonic()))
                    break
                except subprocess.TimeoutExpired:
                    continue
            if p.returncode:
                raise RuntimeError(stderr + stdout)
            result = records(stdout)
            for r in result:
                r.update(peak_sampled_swap_kib=peak_swap, peak_sampled_rss_kib=peak_rss,
                         memory_samples=samples, memory_sampling_interval_s=0.5)
            return result
        finally:
            if p.poll() is None:
                p.kill(); p.communicate()
    with link(profile) as names:
        processes = []
        try:
            for role in range(2):
                command = ["ip", "netns", "exec", names[role], str(exe), *options,
                           "--party", str(role), "--address", "10.203.0.1:12123"]
                processes.append(subprocess.Popen(command, stdout=subprocess.PIPE,
                                                  stderr=subprocess.PIPE, text=True))
                if role == 0:
                    time.sleep(0.15)
            all_records = []
            deadline = time.monotonic() + timeout
            memory = [dict(peak_sampled_swap_kib=0, peak_sampled_rss_kib=0,
                           memory_samples=0, memory_sampling_interval_s=0.5) for _ in processes]
            while True:
                active = [p for p in processes if p.poll() is None]
                if not active:
                    break
                for p, measured in zip(processes, memory):
                    try:
                        fields = dict(line.split(':', 1) for line in
                                      pathlib.Path(f"/proc/{p.pid}/status").read_text().splitlines() if ':' in line)
                        measured['peak_sampled_swap_kib'] = max(measured['peak_sampled_swap_kib'],
                                                              int(fields.get('VmSwap', '0 kB').split()[0]))
                        measured['peak_sampled_rss_kib'] = max(measured['peak_sampled_rss_kib'],
                                                             int(fields.get('VmRSS', '0 kB').split()[0]))
                        measured['memory_samples'] += 1
                    except FileNotFoundError:
                        pass
                remaining = deadline - time.monotonic()
                if remaining <= 0:
                    raise subprocess.TimeoutExpired(active[0].args, timeout)
                try:
                    active[0].communicate(timeout=min(0.5, remaining))
                except subprocess.TimeoutExpired:
                    pass
            for p, measured in zip(processes, memory):
                stdout, stderr = p.communicate(timeout=max(1, deadline - time.monotonic()))
                if p.returncode:
                    raise RuntimeError(stderr + stdout)
                result = records(stdout)
                for r in result:
                    r.update(measured)
                all_records.extend(result)
            return all_records
        finally:
            for p in processes:
                if p.poll() is None:
                    p.terminate()
                    try:
                        p.communicate(timeout=3)
                    except subprocess.TimeoutExpired:
                        p.kill()
                        p.communicate()


def numbers(s):
    return [int(x) for x in s.split(",")]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--exe", type=pathlib.Path, default=pathlib.Path("out/build/linux/frontend/logstar"))
    parser.add_argument("--sizes", type=numbers, default=[1024, 4096])
    parser.add_argument("--bits", type=numbers, default=[32])
    parser.add_argument("--bases", type=numbers, default=[8, 16])
    parser.add_argument("--blocks", type=numbers, default=[0])
    parser.add_argument("--batch-sizes", type=numbers, default=[262144])
    parser.add_argument("--concurrency", type=int, default=2)
    parser.add_argument("--profiles", default="local")
    parser.add_argument("--patterns", default="random")
    parser.add_argument("--trials", type=int, default=3)
    parser.add_argument("--timeout", type=float, default=600)
    parser.add_argument("--output", type=pathlib.Path, default=pathlib.Path("out/logstar/results.jsonl"))
    args = parser.parse_args()
    profiles = args.profiles.split(",")
    if any(p not in {"local", *PROFILES} for p in profiles):
        parser.error("profiles: local,tcp,lan,metro,wan,slow")
    exe = args.exe.resolve(strict=True)
    if args.trials < 1:
        parser.error("trials must be positive")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    binary_hash = hashlib.sha256(exe.read_bytes()).hexdigest()
    metadata = {"type": "environment", "platform": platform.platform(),
                "cpu_count": os.cpu_count(), "executable": str(exe),
                "binary_sha256": binary_hash,
                "run_id": uuid.uuid4().hex,
                "profiles": PROFILES, "argv": sys.argv,
                "utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())}
    if pathlib.Path("/proc/cpuinfo").exists():
        metadata["cpu_model"] = next((line.partition(":")[2].strip()
            for line in pathlib.Path("/proc/cpuinfo").read_text().splitlines()
            if line.startswith("model name")), "unknown")
    with args.output.open("a", encoding="utf-8") as out:
        out.write(json.dumps(metadata) + "\n")
        out.flush()
        for n, bits, base, block, batch, profile, pattern, repeat in itertools.product(
                args.sizes, args.bits, args.bases, args.blocks, args.batch_sizes,
                profiles, args.patterns.split(","), range(args.trials)):
            opts = ["--n", str(n), "--bits", str(bits), "--base", str(base),
                    "--block", str(block), "--batch-size", str(batch),
                    "--concurrency", str(args.concurrency), "--pattern", pattern,
                    "--seed", str(repeat)]
            print(f"n={n} bits={bits} base={base} block={block} batch={batch} {profile} trial={repeat}",
                  file=sys.stderr, flush=True)
            trial_id = uuid.uuid4().hex
            for record in trial(exe, opts, profile, args.timeout):
                record.update(profile=profile, trial=repeat, trial_id=trial_id,
                              run_id=metadata["run_id"], binary_sha256=binary_hash)
                out.write(json.dumps(record) + "\n")
                out.flush()


if __name__ == "__main__":
    main()
